const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');
const crypto = require('node:crypto');
const assert = require('node:assert/strict');
const { execFileSync } = require('node:child_process');
const gm = require('../dist/main/main/infra/git.js');
const { Engine } = require('../dist/main/main/engine.js');
const { SettingsStore } = require('../dist/main/main/infra/settings.js');
const { loadTransport } = require('../dist/main/main/transport.js');
(async () => {
  const root = await fs.realpath(await fs.mkdtemp(path.join(os.tmpdir(), 'reposync-working-')));
  const actualResolve = gm.resolveSource; const actualRefresh = gm.refreshSource;
  const git = (dir, args) => execFileSync('git', args, { cwd: dir, stdio: 'pipe' }).toString().trim();
  const commit = (dir) => { git(dir, ['add', '.']); git(dir, ['-c', 'user.name=QA', '-c', 'user.email=qa@example.invalid', 'commit', '-m', 'Тестовое состояние']); };
  try {
    const remote = path.join(root, 'remote'); const local = path.join(root, 'local'); const output = path.join(root, 'output');
    await fs.mkdir(remote); await fs.mkdir(output); git(remote, ['init', '-b', 'main']);
    for (const [name, bytes] of [['common.txt', 'base\n'], ['deleted.txt', 'remove'], ['.gitignore', 'ignored/\n']]) await fs.writeFile(path.join(remote, name), bytes);
    commit(remote); git(root, ['clone', remote, local]);
    await fs.writeFile(path.join(remote, 'common.txt'), 'incoming\r\n'); commit(remote);
    const profile = { id: crypto.randomUUID(), name: 'Рабочая копия', role: 'internal', sources: { internal: { kind: 'local', location: local, branch: 'main' }, global: { kind: 'remote', location: 'https://example.invalid/test.git', branch: 'main' } }, commitRequired: true, exclusions: ['excluded.txt'], includeIgnored: [], maxPartMB: 1, transportMode: 'compact' };
    const store = new SettingsStore(path.join(root, 'settings')); await store.load();
    await store.save({ schemaVersion: 6, globalExclusions: [], profiles: [profile], outputDirectory: output, lastRepositories: [] });
    gm.refreshSource = async () => ({ changedBranches: [], branches: ['main'], commits: [], baseCommits: [] });
    gm.resolveSource = async (source, mode, cache) => source.kind === 'remote' ? { ...await actualResolve({ ...source, kind: 'local', location: remote }, 'internal', cache), source } : actualResolve(source, mode, cache);
    const engine = new Engine(store);
    await fs.writeFile(path.join(local, 'common.txt'), 'staged\n'); git(local, ['add', 'common.txt']);
    await fs.writeFile(path.join(local, 'common.txt'), 'working\r\n');
    await fs.writeFile(path.join(local, 'new.bin'), Buffer.from([0, 255, 1]));
    await fs.writeFile(path.join(local, 'excluded.txt'), 'excluded');
    await fs.mkdir(path.join(local, 'ignored')); await fs.writeFile(path.join(local, 'ignored/private.txt'), 'ignore');
    await fs.rm(path.join(local, 'deleted.txt'));
    let analysis = await engine.analyze(profile.id, 'outgoing', undefined, { mode: 'commit' });
    assert.equal((await engine.previewCode(analysis.token, 'common.txt')).after, 'base\n');
    assert(!analysis.entries.some(file => file.path === 'new.bin'));
    analysis = await engine.analyze(profile.id, 'outgoing', undefined, { mode: 'working' });
    assert(analysis.state.startsWith('content:'));
    assert.equal((await engine.previewCode(analysis.token, 'common.txt')).after, 'working\r\n');
    assert(analysis.entries.some(file => file.path === 'deleted.txt' && file.operation === 'DELETE'));
    assert(analysis.entries.some(file => file.path === 'new.bin'));
    assert(!analysis.entries.some(file => file.path.startsWith('ignored/') || file.path === 'excluded.txt'));
    await engine.selectExport(analysis.token, ['common.txt', 'new.bin']);
    await fs.writeFile(path.join(local, 'common.txt'), 'changed');
    await assert.rejects(engine.exportPackage(analysis.token, [], false), /Источник изменился/);
    analysis = await engine.analyze(profile.id, 'outgoing', undefined, { mode: 'working' });
    await engine.selectExport(analysis.token, ['new.bin']);
    await fs.writeFile(path.join(local, 'common.txt'), 'unselected change');
    const artifacts = await engine.exportPackage(analysis.token, [], false);
    const transport = await loadTransport(artifacts.filter(name => name.endsWith('.md')));
    assert.deepEqual(transport.records.map(file => file.path), ['new.bin']);
    assert.deepEqual(await fs.readFile(artifacts.find(name => !name.endsWith('.md'))), Buffer.from([0, 255, 1]));
    await engine.discardPending(profile.id);
    const selection = { mode: 'commit', commit: git(remote, ['rev-parse', 'HEAD']) };
    analysis = await engine.analyze(profile.id, 'incoming', selection);
    let preview = await engine.prepareIncoming(analysis.token, ['common.txt']);
    assert.deepEqual(preview.overwritePaths, [{ path: 'common.txt', staged: true }]);
    const indexBefore = git(local, ['ls-files', '--stage']);
    await assert.rejects(engine.applyImport(preview.token), /Подтвердите перезапись/);
    preview = await engine.prepareIncoming(analysis.token, ['common.txt']);
    git(local, ['add', 'common.txt']);
    await assert.rejects(engine.applyImport(preview.token, true), /Git-статус/);
    preview = await engine.prepareIncoming(analysis.token, ['common.txt']);
    const confirmedIndex = git(local, ['ls-files', '--stage']);
    await fs.writeFile(path.join(local, 'common.txt'), 'after preview');
    await assert.rejects(engine.applyImport(preview.token, true), /Локальные файлы изменились/);
    preview = await engine.prepareIncoming(analysis.token, ['common.txt']);
    await engine.applyImport(preview.token, true);
    assert.equal(await fs.readFile(path.join(local, 'common.txt'), 'utf8'), 'incoming\r\n');
    assert.equal(git(local, ['ls-files', '--stage']), confirmedIndex);
    assert.notEqual(indexBefore, confirmedIndex);
    assert.deepEqual(await fs.readFile(path.join(local, 'new.bin')), Buffer.from([0, 255, 1]));
    const backups = await fs.readdir(path.join(store.directory, 'backups'));
    assert(backups.length); const backup = await fs.readFile(path.join(store.directory, 'backups', backups.at(-1), '0.bin'));
    assert.equal(backup.toString(), 'after preview');
    assert.equal(store.get().profiles[0].commitRequired, false);
    analysis = await engine.analyze(profile.id, 'incoming', selection);
    preview = await engine.prepareIncoming(analysis.token, ['common.txt']);
    assert.deepEqual(preview.overwritePaths, []); assert.equal(preview.entries.length, 0);
    await engine.applyImport(preview.token);
    git(local, ['reset', '--hard', 'HEAD']);
    analysis = await engine.analyze(profile.id, 'incoming', selection);
    preview = await engine.prepareIncoming(analysis.token, ['common.txt']);
    assert.deepEqual(preview.overwritePaths, []);
    // Force a post-write error and verify the original bytes and index are restored.
    const save = store.save.bind(store); let fail = true;
    store.save = async settings => { if (fail) { fail = false; throw new Error('fixture write failure'); } return save(settings); };
    const before = await fs.readFile(path.join(local, 'common.txt')); const index = git(local, ['ls-files', '--stage']);
    await assert.rejects(engine.applyImport(preview.token), /fixture write failure/);
    assert.deepEqual(await fs.readFile(path.join(local, 'common.txt')), before);
    assert.equal(git(local, ['ls-files', '--stage']), index);
    const recovery = new Engine(store); await recovery.recover();
    // Recreate an interrupted journal with an original dirty working version.
    const recoveryDir = path.join(store.directory, 'backups', 'interrupted'); await fs.mkdir(recoveryDir);
    const dirtyBytes = Buffer.from('dirty before interrupted apply\r\n'); const incomingBytes = Buffer.from('partial result');
    await fs.writeFile(path.join(recoveryDir, '0.bin'), dirtyBytes); await fs.writeFile(path.join(local, 'common.txt'), incomingBytes);
    await fs.writeFile(path.join(recoveryDir, 'journal.json'), JSON.stringify({ target: local, settingsBefore: store.get(), committed: false, createdDirectories: [], temporaryFiles: [], entries: [{ path: 'common.txt', file: '0.bin', mode: 0o644, beforeSha256: gm.sha256(dirtyBytes), afterSha256: gm.sha256(incomingBytes), touched: true }] }));
    await new Engine(store).recover(); assert.deepEqual(await fs.readFile(path.join(local, 'common.txt')), dirtyBytes);
    assert.equal(git(local, ['ls-files', '--stage']), index);
    // Explicit ignored export, unsupported symlink, and dirty ignored-directory detection.
    const ignoredProfile = { ...profile, includeIgnored: ['ignored/private.txt'] };
    assert((await gm.readWorkingTree(local, ignoredProfile)).files.some(file => file.path === 'ignored/private.txt'));
    await fs.symlink('common.txt', path.join(local, 'link.txt'));
    await assert.rejects(gm.readWorkingTree(local, profile), /символическ|Символические/); await fs.rm(path.join(local, 'link.txt'));
    git(local, ['reset', '--hard', 'HEAD']);
    await fs.mkdir(path.join(remote, 'ignored')); await fs.writeFile(path.join(remote, 'ignored/private.txt'), 'external first'); git(remote, ['add', '-f', 'ignored/private.txt']); commit(remote);
    await fs.writeFile(path.join(remote, 'ignored/private.txt'), 'external next'); commit(remote);
    analysis = await engine.analyze(profile.id, 'incoming', { mode: 'commit', commit: git(remote, ['rev-parse', 'HEAD']) });
    preview = await engine.prepareIncoming(analysis.token, ['ignored/private.txt']);
    assert.deepEqual(preview.overwritePaths, [{ path: 'ignored/private.txt', staged: false }]);
    await engine.applyImport(preview.token, true);
    assert.equal(await fs.readFile(path.join(local, 'ignored/private.txt'), 'utf8'), 'external next');
    // DELETE/RENAME checks still enforce source identity; rename target and source both matter.
    git(remote, ['mv', 'common.txt', 'renamed.txt']); commit(remote);
    await fs.writeFile(path.join(local, 'common.txt'), 'incoming\r\n');
    analysis = await engine.analyze(profile.id, 'incoming', { mode: 'commit', commit: git(remote, ['rev-parse', 'HEAD']) });
    preview = await engine.prepareIncoming(analysis.token, ['renamed.txt']);
    assert(preview.overwritePaths.some(file => file.path === 'common.txt'));
    await engine.applyImport(preview.token, true);
    assert.equal(await fs.readFile(path.join(local, 'renamed.txt'), 'utf8'), 'incoming\r\n');
    await fs.writeFile(path.join(local, 'common.txt'), 'different');
    analysis = await engine.analyze(profile.id, 'incoming', { mode: 'commit', commit: git(remote, ['rev-parse', 'HEAD']) });
    const conflictingRename = await engine.prepareIncoming(analysis.token, ['renamed.txt']);
    assert.match(conflictingRename.conflicts[0].message, /Локальное содержимое отличается/);
    git(local, ['rm', '--cached', 'common.txt']);
    assert((await gm.workingPaths(local)).get('common.txt').staged);
    await fs.writeFile(path.join(local, '.git', 'MERGE_HEAD'), git(local, ['rev-parse', 'HEAD']));
    await assert.rejects(gm.requireLocalReady(profile.sources.internal), /Незавершённая операция Git/); await fs.rm(path.join(local, '.git', 'MERGE_HEAD'));

    git(local, ['checkout', '-b', 'other']);
    await assert.rejects(engine.analyze(profile.id, 'outgoing', undefined, { mode: 'working' }), /Для применения нужна ветка/);
    console.log('Working-tree checks passed: commit/working export, CRLF/binary/deletion/exclusions, selected stale guard, overwrite consent, index/status guards, backup/no-op/unrelated edits, rollback/interrupted recovery, ignored export/apply, symlink/rename/merge guards, branch guard. Remote I/O mocked.');
  } finally { gm.resolveSource = actualResolve; gm.refreshSource = actualRefresh; await fs.rm(root, { recursive: true, force: true }); }
})().catch(error => { console.error(error); process.exitCode = 1; });
