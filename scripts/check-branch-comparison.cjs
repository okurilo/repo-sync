const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');
const crypto = require('node:crypto');
const assert = require('node:assert/strict');
const { execFileSync } = require('node:child_process');
const gitModule = require('../dist/main/main/infra/git.js');
const { Engine, parseIncomingSelection } = require('../dist/main/main/engine.js');
const { SettingsStore } = require('../dist/main/main/infra/settings.js');

(async () => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'reposync-branches-'));
  const actualResolve = gitModule.resolveSource;
  const actualRefresh = gitModule.refreshSource;
  const git = (dir, args) => execFileSync('git', args, { cwd: dir, stdio: 'pipe' }).toString().trim();
  const commit = (dir, message) => { git(dir, ['add', '.']); git(dir, ['-c', 'user.name=QA', '-c', 'user.email=qa@example.invalid', 'commit', '-m', message]); };
  try {
    const remote = path.join(root, 'external'); const local = path.join(root, 'local');
    await fs.mkdir(remote); git(remote, ['init', '-b', 'main']);
    await fs.writeFile(path.join(remote, 'common.txt'), 'base\n'); commit(remote, 'base');
    git(remote, ['checkout', '-b', 'feature']);
    await fs.writeFile(path.join(remote, 'common.txt'), 'feature\r\n');
    await fs.writeFile(path.join(remote, 'b-only.txt'), 'B'); commit(remote, 'feature');
    git(remote, ['checkout', 'main']);
    await fs.writeFile(path.join(remote, 'common.txt'), 'new main\n');
    await fs.writeFile(path.join(remote, 'a-only.txt'), 'A'); commit(remote, 'main advanced');
    git(root, ['clone', '--branch', 'main', remote, local]);
    await fs.writeFile(path.join(local, 'receiver-only.txt'), 'preserve'); commit(local, 'receiver');
    const profile = { id: crypto.randomUUID(), name: 'Branches QA', role: 'internal', sources: { internal: { kind: 'local', location: local, branch: 'main' }, global: { kind: 'remote', location: 'https://example.invalid/branches.git', branch: 'feature' } }, exclusions: [], includeIgnored: [], maxPartMB: 1, transportMode: 'compact' };
    const store = new SettingsStore(path.join(root, 'settings')); await store.load();
    await store.save({ schemaVersion: 6, globalExclusions: [], profiles: [profile], outputDirectory: '', lastRepositories: [] });
    gitModule.refreshSource = async () => ({ changedBranches: [], branches: ['main', 'feature'], commits: [], baseCommits: [] });
    gitModule.resolveSource = async (source, mode, cache) => source.kind === 'remote' ? { ...await actualResolve({ ...source, kind: 'local', location: remote }, 'internal', cache), source } : actualResolve(source, mode, cache);
    const engine = new Engine(store); const selection = { mode: 'branches', baseBranch: 'main', branch: 'feature' };
    assert.deepEqual(parseIncomingSelection(selection), { ...selection, commit: undefined, from: undefined });
    assert.throws(() => parseIncomingSelection({ mode: 'branches', branch: 'feature' }));
    assert.throws(() => parseIncomingSelection({ ...selection, commit: 'a'.repeat(40) }));
    assert.throws(() => parseIncomingSelection({ ...selection, from: 'a'.repeat(40) }));
    await assert.rejects(engine.analyze(profile.id, 'incoming', { ...selection, branch: 'main' }), /две разные ветки/);
    let comparison = await engine.analyze(profile.id, 'incoming', selection);
    assert.equal(comparison.sourceState, git(remote, ['rev-parse', 'main']));
    assert.equal(comparison.state, git(remote, ['rev-parse', 'feature']));
    assert(comparison.entries.some(file => file.path === 'a-only.txt' && file.operation === 'DELETE'));
    assert(comparison.entries.some(file => file.path === 'b-only.txt' && file.operation === 'ADD'));
    assert.equal((await engine.previewCode(comparison.token, 'common.txt')).before, 'new main\n');
    const legacy = await engine.analyze(profile.id, 'incoming', { ...selection, mode: 'branch' });
    assert(!legacy.entries.some(file => file.path === 'a-only.txt'));
    comparison = await engine.analyze(profile.id, 'incoming', selection);
    const preview = await engine.prepareIncoming(comparison.token, ['common.txt']);
    await engine.applyImport(preview.token);
    assert.equal(await fs.readFile(path.join(local, 'common.txt'), 'utf8'), 'feature\r\n');
    assert.equal(await fs.readFile(path.join(local, 'a-only.txt'), 'utf8'), 'A');
    assert.equal(await fs.readFile(path.join(local, 'receiver-only.txt'), 'utf8'), 'preserve');
    assert.equal(store.get().profiles[0].baseline, undefined);
    git(local, ['checkout', '--', 'common.txt']);
    comparison = await engine.analyze(profile.id, 'incoming', selection);
    await fs.writeFile(path.join(remote, 'new-a.txt'), 'advance'); commit(remote, 'advance A');
    await assert.rejects(engine.prepareIncoming(comparison.token, ['common.txt']), /Исходная ветка A изменилась/);
    comparison = await engine.analyze(profile.id, 'incoming', selection);
    git(remote, ['checkout', 'feature']); await fs.writeFile(path.join(remote, 'new-b.txt'), 'advance'); commit(remote, 'advance B');
    await assert.rejects(engine.prepareIncoming(comparison.token, ['common.txt']), /Внешняя ветка изменилась/);
    git(remote, ['checkout', '--orphan', 'unrelated']); git(remote, ['rm', '-rf', '.']);
    await fs.writeFile(path.join(remote, 'unrelated.txt'), 'root'); commit(remote, 'unrelated root');
    comparison = await engine.analyze(profile.id, 'incoming', { ...selection, branch: 'unrelated' });
    assert.equal(comparison.state, git(remote, ['rev-parse', 'unrelated']));
    assert(comparison.entries.some(file => file.path === 'unrelated.txt' && file.operation === 'ADD'));
    console.log('Branch comparison checks passed: direct heads, divergence/unrelated histories, legacy merge-base, validation, selected Apply/CRLF, baseline preservation and A/B advance guards. Remote I/O mocked.');
  } finally { gitModule.resolveSource = actualResolve; gitModule.refreshSource = actualRefresh; await fs.rm(root, { recursive: true, force: true }); }
})().catch(error => { console.error(error); process.exitCode = 1; });
